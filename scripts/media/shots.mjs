import { chromium } from "playwright-core";
import path from "node:path";
import { ROOT, WORK, SHOTS, BASE, hostKey, sleep, HERE } from "./paths.mjs";
const key = hostKey();
const b = await chromium.launch({ channel: "chrome" });
const host = await (await b.newContext({ viewport: { width: 1600, height: 900 } })).newPage();
const phone = await (await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, colorScheme: "light" })).newPage();
const shot = (p, n) => p.screenshot({ path: path.join(SHOTS, n + ".jpg"), type: "jpeg", quality: 82 });
const until = async (p, fn, t = 90000) => { const e = Date.now() + t; while (Date.now() < e) { if (await p.evaluate(fn)) return; await sleep(100); } throw new Error("timeout " + fn); };
await host.goto(`${BASE}/host?key=${key}`); await sleep(1500); await host.keyboard.press("h");
await phone.goto(BASE + "/"); await phone.waitForSelector("#emoji-grid button");
await phone.fill("#nick", "มิ้น"); await phone.locator("#emoji-grid button").nth(5).click();
await shot(phone, "phone-join"); await phone.click("#join-btn");
await sleep(5000); await shot(host, "host-lobby");
await host.keyboard.press(" ");
await until(phone, () => !document.getElementById("s-intro").hidden); await sleep(2500);
await shot(host, "host-intro"); await shot(phone, "phone-card");
await until(host, () => document.getElementById("race-light")?.classList.contains("green"), 20000);
const tapper = setInterval(() => phone.locator("#tap-btn").dispatchEvent("pointerdown").catch(() => {}), 130);
await sleep(3500); await shot(host, "host-race"); await shot(phone, "phone-tap"); clearInterval(tapper);
await until(host, () => !document.getElementById("h-queue").hidden); await sleep(6500);
await shot(host, "host-lineup"); await shot(phone, "phone-queue");
// first event card (non-gamble), after its "in real life" line appears
await until(host, () => !!document.querySelector("#q-head .ev-card")); await sleep(2600); await shot(host, "host-event");
await until(phone, () => !document.getElementById("gamble-box").hidden); await sleep(2600);
await shot(phone, "phone-gamble"); await shot(host, "host-gamble"); await phone.click("#g-move");
await until(host, () => !!document.querySelector(".call-card")); await sleep(5500);
await shot(host, "host-call");
await shot(phone, (await phone.evaluate(() => !document.getElementById("s-win").hidden)) ? "phone-win-alt" : "phone-call");
await until(phone, () => !document.getElementById("s-guess").hidden); await sleep(1000);
await phone.locator(".g-opt").nth(3).click(); await sleep(6000);
await shot(host, "host-guess"); await shot(phone, "phone-guess");
await until(host, () => !document.getElementById("h-zoom").hidden); await sleep(3000); await shot(host, "host-zoom-guess");
await sleep(11000); await shot(host, "host-zoom");
await sleep(10500); await shot(host, "host-zoom-text"); await shot(phone, "phone-zoom");
await until(host, () => !document.getElementById("h-end").hidden); await sleep(2000);
await shot(host, "host-end"); await shot(phone, "phone-end");
await sleep(22000); await shot(host, "host-end-closing"); await shot(phone, "phone-end-closing");
await b.close(); console.log("done");
